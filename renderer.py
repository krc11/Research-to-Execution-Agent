"""Step 6 – Render the final markdown report from structured data."""

from __future__ import annotations

from typing import List

from schemas import Report, ScoredCandidate, VerifiedFinding


def _comparison_table(scored: List[ScoredCandidate]) -> str:
    """Build a markdown comparison table."""
    if not scored:
        return "_No candidates scored._\n"

    # Collect all criteria names (stable order from first candidate)
    crit_names = [cs.criterion for cs in scored[0].criterion_scores]

    # Header
    header = "| Candidate | " + " | ".join(crit_names) + " | **Total** | **%** | Must-haves |"
    sep = "|---|" + "|".join(["---"] * len(crit_names)) + "|---|---|---|"

    rows: List[str] = []
    for sc in scored:
        ratings = []
        for cs in sc.criterion_scores:
            ids = ", ".join(cs.finding_ids) if cs.finding_ids else "—"
            ratings.append(f"{cs.rating:.1f} ({ids})")
        mh = "✅" if sc.must_have_met else "❌"
        row = f"| **{sc.candidate}** | " + " | ".join(ratings) + f" | {sc.total_score:.1f} | {sc.percentage:.0f}% | {mh} |"
        rows.append(row)

    return "\n".join([header, sep] + rows) + "\n"


def _evidence_ledger(findings: List[VerifiedFinding]) -> str:
    """Build the evidence ledger table."""
    if not findings:
        return "_No verified evidence._\n"

    header = "| ID | Candidate | Criterion | Claim | Quote | URL | Retrieved |"
    sep = "|---|---|---|---|---|---|---|"
    rows: List[str] = []
    for f in findings:
        # Truncate quote for table readability
        short_quote = (f.quote[:80] + "…") if len(f.quote) > 80 else f.quote
        url_link = f"[link]({f.url})" if f.url.startswith("http") else f.url
        rows.append(
            f"| {f.id} | {f.candidate} | {f.criterion} | {f.claim} | _{short_quote}_ | {url_link} | {f.retrieved_at[:10]} |"
        )

    return "\n".join([header, sep] + rows) + "\n"


def _unverified_section(findings: List[VerifiedFinding]) -> str:
    """Build the 'Could not verify' section."""
    if not findings:
        return "_All claims verified._\n"

    lines: List[str] = []
    for f in findings:
        lines.append(
            f"- **{f.id}** ({f.candidate} / {f.criterion}): {f.claim}  \n"
            f"  _Note: {f.verification_note}_"
        )
    return "\n".join(lines) + "\n"


def render_report(report: Report) -> str:
    """Return the complete markdown report."""

    md = f"""# Research Report

> **Question:** {report.question}
> **Generated:** {report.generated_at}

---

## Recommendation

{report.recommendation}

---

## Comparison Table

{_comparison_table(report.scored_candidates)}

---

## Evidence Ledger

{_evidence_ledger(report.verified_findings)}

---

## Could Not Verify

{_unverified_section(report.unverified_findings)}

---

_Report generated by Research-to-Execution Agent v1._
"""
    return md
